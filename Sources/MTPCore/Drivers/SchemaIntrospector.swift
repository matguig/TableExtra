import Foundation

public protocol SchemaIntrospector: Sendable {
    func databases() async throws -> [String]
    func schemas(includeSystem: Bool) async throws -> [String]
    func defaultSchema() async throws -> String
    func objects(in schema: String) async throws -> [DBObject]
    func tableDetails(schema: String, name: String) async throws -> TableDetails
    /// Every table/view of a schema with columns, indexes and constraints (diagram, diff, codegen, AI context).
    func snapshot(schema: String) async throws -> [TableDetails]
    /// Lightweight table → columns map for autocomplete.
    func columnsByTable(schema: String) async throws -> [String: [ColumnDef]]
    func ddl(for object: DBObject) async throws -> String
    func exactCount(schema: String, name: String) async throws -> Int64
}

public enum Introspection {
    public static func make(_ client: DBClient) -> SchemaIntrospector {
        switch client.config.driver {
        case .postgres: return PostgresIntrospector(client: client)
        case .sqlite: return SQLiteIntrospector(client: client)
        }
    }

    static let separator = "\u{1f}"

    static func split(_ s: String?) -> [String] {
        guard let s, !s.isEmpty else { return [] }
        return s.components(separatedBy: separator)
    }
}

/// Builds CREATE TABLE text from introspected details (shared by drivers, diff and AI context).
public enum DDLWriter {
    public static func createTable(_ t: TableDetails, dialect: SQLDialect, includeIndexes: Bool = true) -> String {
        var lines: [String] = t.columns.map { c in
            var l = "  \(dialect.quoteIdentIfNeeded(c.name)) \(c.dataType)"
            if c.isIdentity { l += " GENERATED BY DEFAULT AS IDENTITY" }
            if !c.isNullable { l += " NOT NULL" }
            if let d = c.defaultValue, !c.isIdentity { l += " DEFAULT \(d)" }
            return l
        }
        for con in t.constraints {
            lines.append("  CONSTRAINT \(dialect.quoteIdentIfNeeded(con.name)) \(con.definition)")
        }
        var sql = "CREATE TABLE \(dialect.qualified(schema: t.object.schema, name: t.object.name)) (\n" + lines.joined(separator: ",\n") + "\n);"
        if includeIndexes {
            let constraintNames = Set(t.constraints.map(\.name))
            for idx in t.indexes where !idx.isPrimary && !constraintNames.contains(idx.name) && !idx.definition.isEmpty {
                sql += "\n\(idx.definition);"
            }
        }
        if let comment = t.object.comment, !comment.isEmpty {
            sql += "\nCOMMENT ON TABLE \(dialect.qualified(schema: t.object.schema, name: t.object.name)) IS \(dialect.quoteLiteral(comment));"
        }
        for c in t.columns {
            if let comment = c.comment, !comment.isEmpty {
                sql += "\nCOMMENT ON COLUMN \(dialect.qualified(schema: t.object.schema, name: t.object.name)).\(dialect.quoteIdentIfNeeded(c.name)) IS \(dialect.quoteLiteral(comment));"
            }
        }
        for trg in t.triggers { sql += "\n\(trg.definition);" }
        return sql
    }

    /// Compact schema summary for LLM prompts: one line per table.
    public static func compactSummary(_ tables: [TableDetails]) -> String {
        tables.map { t in
            let cols = t.columns.map { c -> String in
                var s = "\(c.name) \(c.udtName)"
                if c.isPrimaryKey { s += " pk" }
                if let fk = c.foreignKey { s += " → \(fk.refTable).\(fk.refColumns.first ?? "")" }
                if let e = c.enumValues { s += " {\(e.joined(separator: "|"))}" }
                return s
            }
            return "\(t.object.qualifiedName)(\(cols.joined(separator: ", ")))"
        }.joined(separator: "\n")
    }
}
