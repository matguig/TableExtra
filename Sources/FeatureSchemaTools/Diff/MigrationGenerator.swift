import Foundation
import MTPCore

public struct MigrationOptions: Sendable, Hashable {
    /// DROP TABLE / COLUMN / INDEX / CONSTRAINT / TYPE are emitted commented-out unless this is on.
    public var includeDestructive: Bool
    public var wrapInTransaction: Bool
    /// Section headers and explanatory notes.
    public var includeComments: Bool

    public init(includeDestructive: Bool = false, wrapInTransaction: Bool = true, includeComments: Bool = true) {
        self.includeDestructive = includeDestructive
        self.wrapInTransaction = wrapInTransaction
        self.includeComments = includeComments
    }
}

public struct MigrationStatement: Hashable, Sendable {
    /// Execution order. Types and tables come first, foreign keys after every table exists, drops of whole objects last.
    public enum Phase: Int, Comparable, Sendable, CaseIterable {
        case preamble, types, sequences, dropViews, dropConstraints, dropIndexes, createTables, addColumns, alterColumns,
             dropColumns, addConstraints, createIndexes, foreignKeys, sequenceOwnership, views, dropTables, dropTypes

        public static func < (a: Phase, b: Phase) -> Bool { a.rawValue < b.rawValue }

        var title: String {
            switch self {
            case .preamble: return "Session"
            case .types: return "Types"
            case .sequences: return "Sequences"
            case .dropViews: return "Views to drop"
            case .dropConstraints: return "Constraints to drop"
            case .dropIndexes: return "Indexes to drop"
            case .createTables: return "New tables"
            case .addColumns: return "New columns"
            case .alterColumns: return "Column changes"
            case .dropColumns: return "Columns to drop"
            case .addConstraints: return "Constraints"
            case .createIndexes: return "Indexes"
            case .foreignKeys: return "Foreign keys"
            case .sequenceOwnership: return "Sequence ownership"
            case .views: return "Views"
            case .dropTables: return "Tables to drop"
            case .dropTypes: return "Types to drop"
            }
        }
    }

    public var phase: Phase
    /// One statement, terminated by ";" (or a pure comment when `isNoteOnly`).
    public var sql: String
    public var isDestructive: Bool
    /// Comment printed above the statement.
    public var note: String?
    /// The table / type / view the statement is about.
    public var object: String?

    public init(phase: Phase, sql: String, isDestructive: Bool = false, note: String? = nil, object: String? = nil) {
        self.phase = phase
        self.sql = sql
        self.isDestructive = isDestructive
        self.note = note
        self.object = object
    }

    /// Notes for changes that cannot be expressed as SQL (no statement to run).
    public var isNoteOnly: Bool { sql.isEmpty }
}

public struct MigrationScript: Sendable, Hashable {
    public var statements: [MigrationStatement]
    public var options: MigrationOptions
    public var sourceSchema: String
    public var targetSchema: String

    /// Statements in execution order (stable within a phase).
    public var orderedStatements: [MigrationStatement] {
        statements.enumerated().sorted { a, b in
            a.element.phase == b.element.phase ? a.offset < b.offset : a.element.phase < b.element.phase
        }.map(\.element)
    }

    /// What actually runs: destructive statements only when enabled, no pure notes.
    public var executableStatements: [MigrationStatement] {
        orderedStatements.filter { !$0.isNoteOnly && (!$0.isDestructive || options.includeDestructive) }
    }

    public var hasDestructiveStatements: Bool { statements.contains { $0.isDestructive && !$0.isNoteOnly } }
    /// No statements and no notes besides the session preamble (SQLite changes may be notes only).
    public var isEmpty: Bool { !statements.contains { $0.phase != .preamble } }

    public var sql: String { render() }

    public func render() -> String {
        var out: [String] = []
        if options.includeComments {
            out.append("-- Migration generated by TableExtra")
            out.append("-- Makes target schema \(targetSchema) match source schema \(sourceSchema).")
            if hasDestructiveStatements && !options.includeDestructive {
                out.append("-- Destructive statements are commented out (enable \"Include destructive changes\" to run them).")
            }
        }
        if isEmpty {
            out.append("-- No differences: target already matches source.")
            return out.joined(separator: "\n") + "\n"
        }
        if options.wrapInTransaction { out.append(""); out.append("BEGIN;") }
        var currentPhase: MigrationStatement.Phase?
        for st in orderedStatements {
            if st.phase != currentPhase {
                currentPhase = st.phase
                out.append("")
                if options.includeComments { out.append("-- \(st.phase.title)") }
            }
            if options.includeComments, let note = st.note {
                for line in note.split(separator: "\n", omittingEmptySubsequences: false) { out.append("-- \(line)") }
            }
            guard !st.isNoteOnly else { continue }
            if st.isDestructive && !options.includeDestructive {
                for line in st.sql.split(separator: "\n", omittingEmptySubsequences: false) { out.append("-- \(line)") }
            } else {
                out.append(st.sql)
            }
        }
        if options.wrapInTransaction { out.append(""); out.append("COMMIT;") }
        return out.joined(separator: "\n") + "\n"
    }
}

/// Turns a `SchemaDiffResult` into ordered SQL that makes the target schema look like the source.
public enum MigrationGenerator {
    public static func generate(_ diff: SchemaDiffResult, dialect: SQLDialect = SQLDialect(kind: .postgres),
                                options: MigrationOptions = MigrationOptions()) -> MigrationScript {
        var b = Builder(diff: diff, dialect: dialect)
        b.build()
        return MigrationScript(statements: b.statements, options: options, sourceSchema: diff.sourceSchema, targetSchema: diff.targetSchema)
    }

    struct Builder {
        let diff: SchemaDiffResult
        let dialect: SQLDialect
        let rt: SchemaRetargeter
        var statements: [MigrationStatement] = []
        var isPostgres: Bool { dialect.kind == .postgres }

        init(diff: SchemaDiffResult, dialect: SQLDialect) {
            self.diff = diff
            self.dialect = dialect
            self.rt = SchemaRetargeter(sourceSchema: diff.sourceSchema, targetSchema: diff.targetSchema, dialect: dialect,
                                       enumNames: diff.sourceEnumNames)
        }

        func id(_ name: String) -> String { dialect.quoteIdentIfNeeded(name) }
        func table(_ name: String) -> String { rt.qualified(name) }

        mutating func add(_ phase: MigrationStatement.Phase, _ sql: String, destructive: Bool = false, note: String? = nil, object: String? = nil) {
            statements.append(MigrationStatement(phase: phase, sql: sql, isDestructive: destructive, note: note, object: object))
        }

        mutating func build() {
            guard !diff.isEmpty else { return }
            if isPostgres && diff.sourceSchema != diff.targetSchema {
                let path = diff.targetSchema == "public" ? id(diff.targetSchema) : "\(id(diff.targetSchema)), public"
                add(.preamble, "SET LOCAL search_path TO \(path);",
                    note: "Unqualified names in view bodies and expressions resolve to the target schema.\nSET LOCAL only lasts until COMMIT; outside a transaction use SET.")
            }
            enums()
            for t in diff.tables {
                switch t.change {
                case .added: createTable(t)
                case .removed: dropTable(t)
                case .changed: alterTable(t)
                }
            }
            orderDropTables()
            views()
        }

        // MARK: Enums

        mutating func enums() {
            for e in diff.enums {
                let q = table(e.name)
                switch e.change {
                case .added:
                    guard isPostgres, let s = e.source else { continue }
                    add(.types, "CREATE TYPE \(q) AS ENUM (\(s.values.map { dialect.quoteLiteral($0) }.joined(separator: ", ")));", object: e.name)
                case .removed:
                    guard isPostgres else { continue }
                    add(.dropTypes, "DROP TYPE \(q);", destructive: true, object: e.name)
                case .changed:
                    guard isPostgres, let s = e.source, let t = e.target else { continue }
                    var present = t.values
                    for (i, v) in s.values.enumerated() where !present.contains(v) {
                        var position = ""
                        if let prev = s.values[..<i].last(where: { present.contains($0) }) {
                            position = " AFTER \(dialect.quoteLiteral(prev))"
                        } else if let next = s.values[(i + 1)...].first(where: { present.contains($0) }) {
                            position = " BEFORE \(dialect.quoteLiteral(next))"
                        }
                        add(.types, "ALTER TYPE \(q) ADD VALUE IF NOT EXISTS \(dialect.quoteLiteral(v))\(position);",
                            note: present.count == t.values.count ? "New enum values cannot be used in the transaction that adds them." : nil,
                            object: e.name)
                        present.append(v)
                    }
                    if !e.removedValues.isEmpty || e.orderChanged {
                        let what = e.removedValues.isEmpty ? "Label order differs" : "Labels \(e.removedValues.joined(separator: ", ")) only exist in the target"
                        add(.dropTypes, "", destructive: true,
                            note: "\(e.name): \(what). PostgreSQL cannot drop or reorder enum labels; recreate the type (rename, create, ALTER COLUMN … TYPE … USING col::text::\(e.name), drop old) if needed.",
                            object: e.name)
                    }
                }
            }
        }

        // MARK: Tables

        func columnDefinition(_ c: ColumnDef) -> String {
            var l = "\(id(c.name)) \(rt.type(c.dataType))"
            if c.isGenerated, let expr = c.defaultValue {
                l += " GENERATED ALWAYS AS (\(rt.defaultExpression(expr))) STORED"
            } else if c.isIdentity {
                l += " GENERATED BY DEFAULT AS IDENTITY"
            }
            if !c.isNullable { l += " NOT NULL" }
            if let d = c.defaultValue, !c.isIdentity, !c.isGenerated { l += " DEFAULT \(rt.defaultExpression(d))" }
            return l
        }

        func constraintDefinition(_ c: ConstraintDef) -> String {
            guard c.kind == .foreignKey else { return rt.expression(c.definition) }
            return retargetReferences(c)
        }

        /// FOREIGN KEY … REFERENCES <table>(…): the referenced table moves to the target schema when it lived in the source schema.
        func retargetReferences(_ c: ConstraintDef) -> String {
            guard let fk = c.foreignKey, let re = try? NSRegularExpression(
                pattern: "REFERENCES\\s+(?:\"(?:[^\"]|\"\")+\"|[A-Za-z0-9_$]+)(?:\\.(?:\"(?:[^\"]|\"\")+\"|[A-Za-z0-9_$]+))?\\s*\\(") else {
                return rt.expression(c.definition)
            }
            let refSchema = fk.refSchema.isEmpty || fk.refSchema == diff.sourceSchema ? diff.targetSchema : fk.refSchema
            let ref: String
            if dialect.kind == .sqlite {
                ref = id(fk.refTable)
            } else {
                ref = "\(id(refSchema)).\(id(fk.refTable))"
            }
            let def = c.definition
            return re.stringByReplacingMatches(in: def, range: NSRange(def.startIndex..., in: def),
                                               withTemplate: NSRegularExpression.escapedTemplate(for: "REFERENCES \(ref)("))
        }

        func indexStatement(_ idx: IndexDef, tableName: String) -> String {
            let unique = idx.isUnique ? "UNIQUE " : ""
            return "CREATE \(unique)INDEX \(id(idx.name)) ON \(table(tableName)) \(rt.expression(SQLNormalizer.indexBody(idx)));"
        }

        mutating func sequences(for t: TableDetails, columns: [ColumnDef]) {
            guard isPostgres else { return }
            for c in columns {
                guard !c.isIdentity, let seq = sequenceName(inDefault: c.defaultValue) else { continue }
                let asType: String
                switch c.udtName {
                case "int2": asType = " AS smallint"
                case "int4": asType = " AS integer"
                default: asType = ""
                }
                add(.sequences, "CREATE SEQUENCE IF NOT EXISTS \(table(seq))\(asType);", object: t.object.name)
                add(.sequenceOwnership, "ALTER SEQUENCE \(table(seq)) OWNED BY \(table(t.object.name)).\(id(c.name));", object: t.object.name)
            }
        }

        mutating func createTable(_ d: TableDiff) {
            guard let t = d.source else { return }
            sequences(for: t, columns: t.columns)
            var lines = t.columns.map { "  " + columnDefinition($0) }
            for c in t.constraints where c.kind != .foreignKey {
                lines.append("  CONSTRAINT \(id(c.name)) \(constraintDefinition(c))")
            }
            add(.createTables, "CREATE TABLE \(table(t.object.name)) (\n" + lines.joined(separator: ",\n") + "\n);", object: t.object.name)
            if isPostgres {
                if let comment = t.object.comment, !comment.isEmpty {
                    add(.createTables, "COMMENT ON TABLE \(table(t.object.name)) IS \(dialect.quoteLiteral(comment));", object: t.object.name)
                }
                for c in t.columns {
                    if let comment = c.comment, !comment.isEmpty {
                        add(.createTables, "COMMENT ON COLUMN \(table(t.object.name)).\(id(c.name)) IS \(dialect.quoteLiteral(comment));", object: t.object.name)
                    }
                }
            }
            for idx in SchemaDiff.plainIndexes(t) where !idx.definition.isEmpty || !idx.columns.isEmpty {
                add(.createIndexes, indexStatement(idx, tableName: t.object.name), object: t.object.name)
            }
            for c in t.constraints where c.kind == .foreignKey {
                addForeignKey(c, tableName: t.object.name)
            }
            if !t.triggers.isEmpty {
                add(.createTables, "", note: "\(t.object.name): triggers \(t.triggers.map(\.name).joined(separator: ", ")) are not migrated (their functions may differ).",
                    object: t.object.name)
            }
        }

        mutating func addForeignKey(_ c: ConstraintDef, tableName: String) {
            if dialect.kind == .sqlite {
                add(.foreignKeys, "", note: "\(tableName): SQLite cannot add foreign key \(c.name) to an existing table; rebuild the table.", object: tableName)
                return
            }
            add(.foreignKeys, "ALTER TABLE \(table(tableName)) ADD CONSTRAINT \(id(c.name)) \(constraintDefinition(c));", object: tableName)
        }

        mutating func dropTable(_ d: TableDiff) {
            add(.dropTables, "DROP TABLE \(table(d.name));", destructive: true, object: d.name)
        }

        /// Tables referencing other dropped tables go first.
        mutating func orderDropTables() {
            let drops = statements.filter { $0.phase == .dropTables && !$0.isNoteOnly }
            guard drops.count > 1 else { return }
            let removed = Dictionary(diff.tables.filter { $0.change == .removed }.compactMap { d in d.target.map { (d.name, $0) } },
                                     uniquingKeysWith: { a, _ in a })
            var ordered: [String] = []
            var visiting = Set<String>()
            func visit(_ name: String) {
                guard !ordered.contains(name), !visiting.contains(name) else { return }
                visiting.insert(name)
                // Children (tables referencing `name`) must be dropped before it.
                for (other, t) in removed where other != name && t.foreignKeys.contains(where: { $0.refTable == name }) { visit(other) }
                ordered.append(name)
            }
            for name in removed.keys.sorted() { visit(name) }
            let byObject = Dictionary(drops.map { ($0.object ?? "", $0) }, uniquingKeysWith: { a, _ in a })
            statements.removeAll { $0.phase == .dropTables && !$0.isNoteOnly }
            statements.append(contentsOf: ordered.compactMap { byObject[$0] })
        }

        mutating func alterTable(_ d: TableDiff) {
            guard let s = d.source else { return }
            let tn = table(d.name)
            let sqlite = dialect.kind == .sqlite

            // Constraints first: drops of changed/removed ones happen before column changes.
            for c in d.constraints {
                switch c.change {
                case .removed:
                    if sqlite { continue }
                    add(.dropConstraints, "ALTER TABLE \(tn) DROP CONSTRAINT \(id(c.name));", destructive: true, object: d.name)
                case .changed:
                    if sqlite {
                        add(.addConstraints, "", note: "\(d.name): constraint \(c.name) differs; SQLite needs a table rebuild.", object: d.name)
                        continue
                    }
                    if let old = c.renamedFrom {
                        add(.addConstraints, "ALTER TABLE \(tn) RENAME CONSTRAINT \(id(old)) TO \(id(c.name));", object: d.name)
                    } else if let sc = c.source {
                        add(.dropConstraints, "ALTER TABLE \(tn) DROP CONSTRAINT \(id(c.name));",
                            note: "\(d.name).\(c.name) is recreated with the source definition.", object: d.name)
                        if sc.kind == .foreignKey { addForeignKey(sc, tableName: d.name) }
                        else { add(.addConstraints, "ALTER TABLE \(tn) ADD CONSTRAINT \(id(sc.name)) \(constraintDefinition(sc));", object: d.name) }
                    }
                case .added:
                    guard let sc = c.source else { continue }
                    if sc.kind == .foreignKey { addForeignKey(sc, tableName: d.name); continue }
                    if sqlite {
                        add(.addConstraints, "", note: "\(d.name): SQLite cannot add constraint \(sc.name) to an existing table.", object: d.name)
                        continue
                    }
                    add(.addConstraints, "ALTER TABLE \(tn) ADD CONSTRAINT \(id(sc.name)) \(constraintDefinition(sc));", object: d.name)
                }
            }

            let added = d.columns.filter { $0.change == .added }.compactMap(\.source)
            sequences(for: s, columns: added)
            for c in added {
                add(.addColumns, "ALTER TABLE \(tn) ADD COLUMN \(columnDefinition(c));", object: d.name)
            }
            for c in d.columns where c.change == .removed {
                add(.dropColumns, "ALTER TABLE \(tn) DROP COLUMN \(id(c.name));", destructive: true, object: d.name)
            }
            for c in d.columns where c.change == .changed {
                guard let sc = c.source, let tc = c.target else { continue }
                if sqlite {
                    add(.alterColumns, "", note: "\(d.name).\(c.name): \(c.summary) — SQLite cannot alter columns; rebuild the table.", object: d.name)
                    continue
                }
                alterColumn(tn, table: d.name, c, sc, tc)
            }

            for i in d.indexes {
                switch i.change {
                case .added:
                    if let si = i.source { add(.createIndexes, indexStatement(si, tableName: d.name), object: d.name) }
                case .removed:
                    add(.dropIndexes, "DROP INDEX \(table(i.name));", destructive: true, object: d.name)
                case .changed:
                    if let old = i.renamedFrom {
                        add(.createIndexes, sqlite ? "" : "ALTER INDEX \(table(old)) RENAME TO \(id(i.name));",
                            note: sqlite ? "\(i.name) was named \(old) in the target; SQLite cannot rename indexes." : nil, object: d.name)
                    } else if let si = i.source {
                        add(.dropIndexes, "DROP INDEX \(table(i.name));", note: "\(i.name) is recreated with the source definition.", object: d.name)
                        add(.createIndexes, indexStatement(si, tableName: d.name), object: d.name)
                    }
                }
            }
        }

        mutating func alterColumn(_ tn: String, table name: String, _ c: ColumnDiff, _ sc: ColumnDef, _ tc: ColumnDef) {
            let col = id(c.name)
            let prefix = "ALTER TABLE \(tn) ALTER COLUMN \(col)"
            if c.generatedChanged || (sc.isGenerated && c.defaultChanged) {
                add(.alterColumns, "ALTER TABLE \(tn) DROP COLUMN \(col);\nALTER TABLE \(tn) ADD COLUMN \(columnDefinition(sc));", destructive: true,
                    note: "\(name).\(c.name): generated column expression differs; it can only be dropped and re-added.", object: name)
                return
            }
            let targetHasDefault = tc.defaultValue != nil && !tc.isIdentity
            var defaultDropped = false
            if c.identityChanged && tc.isIdentity {
                add(.alterColumns, "\(prefix) DROP IDENTITY IF EXISTS;", object: name)
            }
            if (c.typeChanged || (c.identityChanged && sc.isIdentity)) && targetHasDefault {
                add(.alterColumns, "\(prefix) DROP DEFAULT;", object: name)
                defaultDropped = true
            }
            if c.typeChanged {
                let type = rt.type(sc.dataType)
                add(.alterColumns, "\(prefix) TYPE \(type) USING \(col)::\(type);", object: name)
            }
            if c.identityChanged && sc.isIdentity {
                add(.alterColumns, "\(prefix) ADD GENERATED BY DEFAULT AS IDENTITY;", object: name)
            }
            if !sc.isIdentity {
                if let d = sc.defaultValue, c.defaultChanged || defaultDropped || (c.identityChanged && tc.isIdentity) {
                    add(.alterColumns, "\(prefix) SET DEFAULT \(rt.defaultExpression(d));", object: name)
                } else if sc.defaultValue == nil && c.defaultChanged && !defaultDropped && targetHasDefault {
                    add(.alterColumns, "\(prefix) DROP DEFAULT;", object: name)
                }
            }
            if c.nullabilityChanged {
                add(.alterColumns, "\(prefix) \(sc.isNullable ? "DROP NOT NULL" : "SET NOT NULL");", object: name)
            }
        }

        // MARK: Views

        mutating func views() {
            for v in diff.views {
                let q = table(v.name)
                let keyword = v.kind == .materializedView ? "MATERIALIZED VIEW" : "VIEW"
                switch v.change {
                case .removed:
                    add(.dropViews, "DROP \(keyword) \(q);", destructive: true, object: v.name)
                case .added, .changed:
                    guard let sv = v.source else { continue }
                    if v.change == .changed, let tv = v.target {
                        let oldKeyword = tv.kind == .materializedView ? "MATERIALIZED VIEW" : "VIEW"
                        add(.dropViews, "DROP \(oldKeyword) IF EXISTS \(q);", note: "\(v.name) is recreated with the source definition.", object: v.name)
                    }
                    var body = rt.expression(sv.definition).trimmingCharacters(in: .whitespacesAndNewlines)
                    while body.hasSuffix(";") { body.removeLast() }
                    add(.views, "CREATE \(keyword) \(q) AS\n\(body);", object: v.name)
                    if v.kind == .materializedView, let details = v.sourceDetails {
                        for idx in details.indexes where !idx.definition.isEmpty {
                            add(.views, indexStatement(idx, tableName: v.name), object: v.name)
                        }
                    }
                }
            }
        }
    }
}
